# Issuer HTML (e.g. Microsoft) may use "Income Statements" / "Cash Flows Statements"
# or a "Financial Statements:" prefix. Segment/adjusted variants stay rejected via
# UNSUPPORTED_TABLE. Keep the pattern line-bounded so prose mentions do not match.
STATEMENT = re.compile(
    r"^\s*(?:financial statements:\s*)?(?:consolidated\s+)?"
    r"(?:statements? of (?:operations|income|earnings|cash flows?|comprehensive income|"
    r"shareholders.? equity|stockholders.? equity)|income statements?|"
    r"cash flows? statements?|balance sheets?)\s*$",
    re.I | re.M,
)
YEAR = re.compile(r"\b(?:19|20)\d{2}\b")
NUMBER = r"(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?"
CELL = re.compile(rf"(?:\(\s*{NUMBER}\s*\)|[-\u2212]?{NUMBER}|\u2014|\u2013|-|N/A)", re.I)
CURRENCIES = re.compile(r"\b(?:USD|EUR|GBP|CAD|AUD|JPY|CNY|RMB|INR|CHF|HKD|SGD)\b", re.I)
UNSUPPORTED_TABLE = re.compile(r"\b(?:forecast\w*|projected|projection\w*|pro[ -]?forma|adjusted|non[ -]?gaap|segment\w*|geographic\w*|supplemental)\b", re.I)


def normalized(text):
    return re.sub(r"\s+", " ", text.lower().replace("\u2019", "'").replace("'", "")).strip().rstrip(":")


def _row(line):
    """Return label/cells only if the entire numeric suffix is well formed."""
    match = re.match(r"^(.+?[A-Za-z):])\s+((?:[$\u20ac\u00a3\u00a5]\s*)?(?:[-\u2212]?\d|\(|\u2014|\u2013|N/A|-(?:\s|$)).*)$", line.strip())
    if not match:
        return None
    suffix = re.sub(r"[$\u20ac\u00a3\u00a5]", "", match[2]).strip()
    cells, end = [], 0
    for cell in CELL.finditer(suffix):
        if suffix[end:cell.start()].strip() or (end and cell.start() == end):
            return None
        cells.append(cell[0])
        end = cell.end()
    if not cells or suffix[end:].strip():
        return None
    return match[1], cells
